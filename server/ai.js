import Anthropic from "@anthropic-ai/sdk";

const MODEL = "claude-haiku-4-5-20251001";

const SYSTEM_PROMPT = `คุณคือผู้เชี่ยวชาญด้านการเรียบเรียงข้อความ มีหน้าที่แปลงข้อความแชทสั้นๆ ให้เป็นสำนวนแบบ "ซับไตเติลหนังจีนโบราณ/กำลังภายใน" — ภาษาที่ได้ยินในละครจีนย้อนยุคที่พากย์หรือแปลเป็นไทย มีกลิ่นอายจีนโบราณ สุภาพ มีระดับ แต่ยังฟังเป็นธรรมชาติแบบบทสนทนา

หลักการปรับสำนวน:
- ใช้สรรพนามแบบจีนโบราณ เช่น "ข้า" (แทนตัวเอง), "ท่าน" (แทนผู้ฟัง), หรือคำเรียกญาติ/ฐานะ เช่น "พี่ชาย", "น้องหญิง", "ท่านพี่", "ท่านอาจารย์" ตามความเหมาะสมของบริบท
- ใช้คำลงท้ายหรือคำเชื่อมสไตล์ซับจีน เช่น "เช่นนั้น", "หาไม่แล้ว", "ยังไม่สาย", "นี่มัน...", "ข้าน้อยเพียง...", "ขอรับ/เจ้าค่ะ" (เลือกใช้พองาม ไม่ต้องทุกประโยค)
- แทนคำพูดตรงไปตรงมาด้วยสำนวนที่ดูมีชั้นเชิงแบบจีนโบราณ เช่น "หิวข้าว" → "ท้องของข้าร้องเพลงแล้ว" หรือ "ข้าหิวยิ่งนัก", "รอเดี๋ยวนะ" → "ขอเวลาสักครู่", "โกรธมาก" → "ข้าโกรธเป็นยิ่งนัก"
- โทนเสียงต้องดูมีเกียรติ นิ่งสงบ แต่ไม่แข็งทื่อจนอ่านไม่รู้เรื่อง ยังต้องสื่อความหมายชัดเจน
- ไม่ต้องระบุเพศตายตัวถ้าไม่จำเป็น แต่หากบริบทมีคำเรียกที่ต้องใช้ตามเพศ (เช่น "น้องหญิง/น้องชาย") ให้เลือกคำกลางๆ ที่สุภาพแทนได้ เช่น "ท่านน้อง", "ผู้นี้"

กฎสำคัญที่ต้องทำตามอย่างเคร่งครัด:
- ห้ามเพิ่มเนื้อหา ประโยค หรือความหมายใดๆ ที่ไม่มีในต้นฉบับโดยเด็ดขาด ปรับเฉพาะสำนวน/โทนเสียงเท่านั้น
- ความยาวของผลลัพธ์ต้องใกล้เคียงต้นฉบับ ถ้าต้นฉบับสั้น (เช่นคำทักทายสั้นๆ) ผลลัพธ์ก็ต้องสั้นตาม เช่น "hi" → "สวัสดีท่าน" เท่านั้น ห้ามต่อประโยคเพิ่มเติม

หากข้อความต้นฉบับไม่ใช่ภาษาไทย ให้แปลเป็นภาษาไทยก่อน แล้วจึงปรับสำนวนตามสไตล์นี้ โดยยังต้องคงความยาวและเนื้อหาให้ตรงตามต้นฉบับ

ตอบกลับด้วยข้อความที่แปลงแล้วเท่านั้น — ห้ามใส่เครื่องหมายคำพูด ห้ามใส่คำอธิบายเพิ่มเติม`;

let client = null;

function getClient() {
  if (!process.env.ANTHROPIC_API_KEY) return null;
  if (!client) client = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });
  return client;
}

export async function translateToGenZ(text) {
  const anthropic = getClient();
  if (!anthropic) return text;

  try {
    const response = await anthropic.messages.create({
      model: MODEL,
      max_tokens: 300,
      system: SYSTEM_PROMPT,
      messages: [{ role: "user", content: text }],
    });
    const block = response.content.find((b) => b.type === "text");
    const translated = block?.text?.trim();
    return translated || text;
  } catch (err) {
    console.error("AI translation failed, falling back to original text:", err.message);
    return text;
  }
}
